#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# work-logger.sh — Automatic daily work logger for Claude Code
#
# Fires on SessionStart, Stop, and SessionEnd hooks.
# Appends structured entries to ~/.claude/daily-log.md
# grouped by date → project, so multi-project days stay clean.
# ─────────────────────────────────────────────────────────────

set -euo pipefail

LOG_FILE="${CLAUDE_DAILY_LOG:-$HOME/.claude/daily-log.md}"
LOCK_DIR="${TMPDIR:-/tmp}/work-logger.lock.d"

# Ensure directory exists
mkdir -p "$(dirname "$LOG_FILE")"

# ── Portable advisory lock (mkdir is atomic on POSIX) ──
# Avoids the `flock` dependency, which is not present on macOS by default.
acquire_lock() {
    local waited=0
    while ! mkdir "$LOCK_DIR" 2>/dev/null; do
        waited=$((waited + 1))
        if [ "$waited" -gt 50 ]; then
            return 1
        fi
        sleep 0.1
    done
    return 0
}

release_lock() {
    rmdir "$LOCK_DIR" 2>/dev/null || true
}

# ── Read hook JSON from stdin ──
INPUT=$(cat)

# ── Parse event type ──
EVENT=$(echo "$INPUT" | python3 -c "
import sys, json
try:
    data = json.load(sys.stdin)
    print(data.get('hook_event_name', data.get('type', 'unknown')))
except:
    print('unknown')
" 2>/dev/null || echo "unknown")

# ── Gather context ──
TODAY=$(date '+%Y-%m-%d')
NOW=$(date '+%H:%M')
PROJECT_DIR=$(pwd)
PROJECT_NAME=$(basename "$PROJECT_DIR")
GIT_BRANCH=$(git -C "$PROJECT_DIR" branch --show-current 2>/dev/null || echo "n/a")

# ── Helper: ensure today's date header AND project subheading exist ──
ensure_headers() {
    local project="$1"

    if [ ! -f "$LOG_FILE" ]; then
        cat > "$LOG_FILE" << 'HEADER'
# Daily Work Log

Auto-generated by Work Logger
Entries are grouped by date → project.

HEADER
    fi

    # Ensure today's date header exists
    if ! grep -q "^## $TODAY" "$LOG_FILE" 2>/dev/null; then
        echo "" >> "$LOG_FILE"
        echo "## $TODAY" >> "$LOG_FILE"
        echo "" >> "$LOG_FILE"
    fi

    # Ensure project subheading exists under today's date
    # We need to check that the ### project line appears AFTER ## TODAY
    # and BEFORE the next ## date (or end of file)
    python3 << PYEOF
import re, sys

with open("$LOG_FILE", "r") as f:
    content = f.read()

today = "$TODAY"
project = "$project"
date_header = f"## {today}"
project_header = f"### {project}"

# Find today's section
date_pos = content.find(date_header)
if date_pos == -1:
    sys.exit(0)  # shouldn't happen, we just added it

# Find the next date section (or end of file)
next_date = re.search(r'^## \d{4}-\d{2}-\d{2}', content[date_pos + len(date_header):], re.MULTILINE)
if next_date:
    section_end = date_pos + len(date_header) + next_date.start()
else:
    section_end = len(content)

today_section = content[date_pos:section_end]

# Check if project subheading already exists in today's section
if project_header not in today_section:
    # Insert project subheading at the end of today's section
    insert_pos = section_end
    insertion = f"\n{project_header}\n"
    content = content[:insert_pos] + insertion + content[insert_pos:]
    with open("$LOG_FILE", "w") as f:
        f.write(content)
PYEOF
}

# ── Helper: append a log line under the correct project section ──
append_log() {
    local project="$1"
    local entry="$2"

    acquire_lock || true
    trap 'release_lock' EXIT INT TERM
    (
        ensure_headers "$project"

        # Append the entry right after the project's ### heading
        python3 << PYEOF
import re

with open("$LOG_FILE", "r") as f:
    lines = f.readlines()

today = "$TODAY"
project = "$project"
entry = "$entry"
date_header = f"## {today}\n"
project_header = f"### {project}\n"

# Find the project heading within today's section
in_today = False
insert_at = None

for i, line in enumerate(lines):
    if line.strip() == f"## {today}":
        in_today = True
        continue
    if in_today and line.startswith("## ") and line.strip() != f"## {today}":
        # We've passed today's section without finding the project
        break
    if in_today and line.strip() == f"### {project}":
        # Found the project heading — find the last entry under it
        # (before the next ### or ## or end of section)
        insert_at = i + 1
        for j in range(i + 1, len(lines)):
            if lines[j].startswith("## ") or lines[j].startswith("### "):
                insert_at = j
                break
            if lines[j].strip():  # non-empty line = an entry
                insert_at = j + 1
            elif not lines[j].strip() and j + 1 < len(lines) and (lines[j+1].startswith("## ") or lines[j+1].startswith("### ")):
                insert_at = j
                break
        break

if insert_at is not None:
    lines.insert(insert_at, entry + "\n")
    with open("$LOG_FILE", "w") as f:
        f.writelines(lines)
PYEOF
    )
    release_lock
}

# ── Handle each event ──
case "$EVENT" in

    SessionStart)
        append_log "$PROJECT_NAME" "- **${NOW}** 🟢 Session started (branch: \`${GIT_BRANCH}\`)"
        ;;

    Stop)
        # Extract a summary of what Claude just did from the hook input
        SUMMARY=$(echo "$INPUT" | python3 -c "
import sys, json
try:
    data = json.load(sys.stdin)

    # Try tool_input for file edits
    tool_input = data.get('tool_input', {})
    if isinstance(tool_input, dict):
        file_path = tool_input.get('file_path', tool_input.get('path', ''))
        if file_path:
            print(f'Edited: {file_path}')
            sys.exit(0)

    # Try to get from transcript — last assistant message
    transcript = data.get('transcript', [])
    last_msg = ''
    if isinstance(transcript, list):
        for msg in reversed(transcript):
            if isinstance(msg, dict) and msg.get('role') == 'assistant':
                content = msg.get('content', '')
                if isinstance(content, list):
                    for block in content:
                        if isinstance(block, dict) and block.get('type') == 'text':
                            last_msg = block.get('text', '')[:200]
                            break
                elif isinstance(content, str):
                    last_msg = content[:200]
                break

    if last_msg:
        lines = [l.strip() for l in last_msg.split('\n') if l.strip() and not l.strip().startswith('#')]
        if lines:
            print(lines[0][:150])
            sys.exit(0)

    print('')
except Exception:
    print('')
" 2>/dev/null || echo "")

        # Only log Stop events with a meaningful summary
        if [ -n "$SUMMARY" ] && [ ${#SUMMARY} -gt 5 ]; then
            append_log "$PROJECT_NAME" "  - ${NOW} ↳ ${SUMMARY}"
        fi
        ;;

    SessionEnd)
        # Capture git diff stat for the session
        GIT_SUMMARY=$(git -C "$PROJECT_DIR" diff --stat HEAD 2>/dev/null | tail -1 || echo "")
        COMMIT_COUNT=$(git -C "$PROJECT_DIR" log --oneline --since="today" 2>/dev/null | wc -l | tr -d ' ' || echo "0")

        END_ENTRY="- **${NOW}** 🔴 Session ended"
        if [ -n "$GIT_SUMMARY" ]; then
            END_ENTRY="${END_ENTRY} — ${GIT_SUMMARY}"
        fi
        if [ "$COMMIT_COUNT" -gt 0 ] 2>/dev/null; then
            END_ENTRY="${END_ENTRY} (${COMMIT_COUNT} commits today)"
        fi
        append_log "$PROJECT_NAME" "$END_ENTRY"
        ;;

    *)
        # Unknown event, skip silently
        ;;
esac

exit 0
