#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# work-logger.sh — Automatic daily work logger for Claude Code
#
# Hook mode (no arguments): reads the hook JSON on stdin and handles
# SessionStart, Stop, and SessionEnd.
#
# Manual mode:
#   work-logger.sh --manual <project>   # entry text on stdin
#   work-logger.sh --show [YYYY-MM-DD]  # print a day's section (default: today)
#
# Appends structured entries to ${CLAUDE_DAILY_LOG:-~/.claude/daily-log.md}
# grouped by date → project, so multi-project days stay clean.
#
# All logic lives in the Python program below. It is passed through a
# quoted heredoc and receives its inputs via argv/env, so nothing from the
# hook payload, Claude's replies, or directory names is ever interpolated
# into code.
# ─────────────────────────────────────────────────────────────

if [ "${1:-}" = "--show" ]; then
    WL_INPUT=""
else
    # Hook JSON (hook mode) or entry text (--manual)
    WL_INPUT=$(cat)
fi
export WL_INPUT

python3 - "$@" << 'PYEOF'
import json, os, re, shutil, subprocess, sys, tempfile, time
from datetime import datetime

LOG_FILE = os.environ.get("CLAUDE_DAILY_LOG") or os.path.expanduser("~/.claude/daily-log.md")
LOCK_DIR = LOG_FILE + ".lock"
LOCK_BUDGET = 3.0     # seconds; must stay well under the hook timeout
LOCK_STALE_AFTER = 15 # seconds; a lock older than this is from a dead run
TAIL_BYTES = 4 * 1024 * 1024
EDIT_TOOLS = {"Edit", "Write", "MultiEdit", "NotebookEdit"}

FILE_HEADER = (
    "# Daily Work Log\n"
    "\n"
    "Auto-generated by Work Logger\n"
    "Entries are grouped by date → project.\n"
)

now = datetime.now()
TODAY = now.strftime("%Y-%m-%d")
NOW = now.strftime("%H:%M")


def one_line(text, limit):
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def git(cwd, *args):
    try:
        out = subprocess.run(
            ["git", "-C", cwd, *args],
            capture_output=True, text=True, timeout=2,
        )
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:
        return ""


# ── Portable advisory lock (mkdir is atomic on POSIX) ──
# The holder's PID is recorded so a lock left behind by a killed run is
# detected and cleared instead of blocking every later hook.
def lock_is_stale():
    try:
        with open(os.path.join(LOCK_DIR, "pid")) as f:
            pid = int(f.read().strip())
        os.kill(pid, 0)
    except ProcessLookupError:
        return True
    except (FileNotFoundError, ValueError, PermissionError):
        pass
    try:
        return time.time() - os.stat(LOCK_DIR).st_mtime > LOCK_STALE_AFTER
    except FileNotFoundError:
        return False


def acquire_lock():
    deadline = time.time() + LOCK_BUDGET
    while True:
        try:
            os.mkdir(LOCK_DIR)
            with open(os.path.join(LOCK_DIR, "pid"), "w") as f:
                f.write(str(os.getpid()))
            return True
        except FileExistsError:
            if lock_is_stale():
                # Rename first so two runs can't both clear the same lock
                grave = f"{LOCK_DIR}.stale.{os.getpid()}"
                try:
                    os.rename(LOCK_DIR, grave)
                    shutil.rmtree(grave, ignore_errors=True)
                except OSError:
                    pass
                continue
            if time.time() > deadline:
                return False
            time.sleep(0.05)


def release_lock():
    try:
        with open(os.path.join(LOCK_DIR, "pid")) as f:
            if f.read().strip() != str(os.getpid()):
                return
    except (FileNotFoundError, ValueError):
        return
    shutil.rmtree(LOCK_DIR, ignore_errors=True)


# ── Log file editing ──
def is_date_header(line):
    return line.startswith("## ")


def is_heading(line):
    return line.startswith("## ") or line.startswith("### ")


def insert_entry(lines, project, entry):
    """Insert entry as the last line under today's `### project` heading."""
    date_header = f"## {TODAY}"
    try:
        start = next(i for i, l in enumerate(lines) if l.rstrip("\n") == date_header)
    except StopIteration:
        while lines and not lines[-1].strip():
            lines.pop()
        lines += ["\n", date_header + "\n"]
        start = len(lines) - 1

    end = next((i for i in range(start + 1, len(lines)) if is_date_header(lines[i])), len(lines))

    project_header = f"### {project}"
    head = next(
        (i for i in range(start + 1, end) if lines[i].rstrip("\n") == project_header),
        None,
    )
    if head is None:
        # New project block at the end of today's section
        at = end
        while at > start + 1 and not lines[at - 1].strip():
            at -= 1
        block = ["\n", project_header + "\n", entry + "\n"]
        if at == end and end < len(lines):
            block.append("\n")  # keep a gap before the next date header
        lines[at:at] = block
        return lines

    block_end = next((i for i in range(head + 1, end) if is_heading(lines[i])), end)
    at = block_end
    while at > head + 1 and not lines[at - 1].strip():
        at -= 1
    lines.insert(at, entry + "\n")
    return lines


def write_entry(project, entry):
    project = one_line(project, 80).lstrip("#").strip() or "General"
    os.makedirs(os.path.dirname(LOG_FILE) or ".", exist_ok=True)
    if not acquire_lock():
        print("work-logger: log is busy, entry skipped", file=sys.stderr)
        return
    try:
        if os.path.exists(LOG_FILE):
            with open(LOG_FILE, encoding="utf-8") as f:
                lines = f.readlines()
        else:
            lines = FILE_HEADER.splitlines(keepends=True)
        if lines and not lines[-1].endswith("\n"):
            lines[-1] += "\n"
        lines = insert_entry(lines, project, entry)
        # Atomic replace so a killed hook never leaves a half-written log
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(LOG_FILE) or ".", prefix=".daily-log.")
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.writelines(lines)
        os.replace(tmp, LOG_FILE)
    finally:
        release_lock()


# ── Stop: summarize the turn that just finished ──
def read_transcript_tail(path):
    try:
        with open(path, "rb") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            f.seek(max(0, size - TAIL_BYTES))
            data = f.read().decode("utf-8", "replace")
    except (OSError, TypeError):
        return []
    rows = data.splitlines()
    if size > TAIL_BYTES:
        rows = rows[1:]  # first line is probably cut in half
    out = []
    for row in rows:
        try:
            out.append(json.loads(row))
        except ValueError:
            pass
    return out


def is_user_prompt(entry):
    if entry.get("type") != "user" or entry.get("isMeta"):
        return False
    content = (entry.get("message") or {}).get("content")
    if isinstance(content, str):
        return True
    if isinstance(content, list):
        kinds = {b.get("type") for b in content if isinstance(b, dict)}
        return "tool_result" not in kinds
    return False


def last_turn(entries):
    """Return (last assistant text, edited file paths) for the latest turn."""
    turn = []
    for entry in reversed(entries):
        if is_user_prompt(entry):
            break
        turn.append(entry)
    turn.reverse()
    text, edited = "", []
    for entry in turn:
        if entry.get("type") != "assistant":
            continue
        for block in (entry.get("message") or {}).get("content") or []:
            if not isinstance(block, dict):
                continue
            if block.get("type") == "text" and block.get("text", "").strip():
                text = block["text"]
            elif block.get("type") == "tool_use" and block.get("name") in EDIT_TOOLS:
                inp = block.get("input") or {}
                path = inp.get("file_path") or inp.get("notebook_path")
                if path and path not in edited:
                    edited.append(path)
    return text, edited


def first_meaningful_line(text):
    in_fence = False
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence or not s or s.startswith(("#", "|", ">")) or set(s) <= set("-*_= "):
            continue
        s = re.sub(r"^([-*+]|\d+\.)\s+", "", s)
        s = s.replace("**", "")
        if s:
            return s
    return ""


def stop_summary(data, cwd):
    text, edited = last_turn(read_transcript_tail(data.get("transcript_path")))
    if isinstance(data.get("last_assistant_message"), str) and data["last_assistant_message"].strip():
        text = data["last_assistant_message"]
    summary = one_line(first_meaningful_line(text), 150)

    def short(path):
        # realpath on both sides: /tmp vs /private/tmp etc. must still match
        real, root = os.path.realpath(path), os.path.realpath(cwd)
        if real.startswith(root + os.sep):
            return os.path.relpath(real, root)
        home = os.path.expanduser("~")
        return "~" + path[len(home):] if path.startswith(home + os.sep) else path

    rel = [short(p) for p in edited]
    files = ", ".join(rel[:3]) + (f" (+{len(rel) - 3} more)" if len(rel) > 3 else "")
    if summary and files:
        return one_line(f"{summary} · edited: {files}", 220)
    if files:
        return one_line(f"Edited: {files}", 220)
    return summary


# ── SessionEnd: what is in the working tree right now ──
def session_end_entry(cwd):
    entry = f"- **{NOW}** 🔴 Session ended"
    stat = git(cwd, "diff", "--shortstat", "HEAD")
    if stat:
        entry += f" — uncommitted: {stat}"
    email = git(cwd, "config", "user.email")
    if git(cwd, "rev-parse", "--is-inside-work-tree") == "true":
        args = ["log", "--oneline", "--since=midnight"]
        if email:
            args.append(f"--author={email}")
        out = git(cwd, *args)
        count = len(out.splitlines()) if out else 0
        if count:
            entry += f" ({count} commit{'s' if count != 1 else ''} by you today)"
    return entry


def show(day):
    if not os.path.exists(LOG_FILE):
        print(f"No daily log found at {LOG_FILE}. The work logger may not be set up yet.")
        return
    with open(LOG_FILE, encoding="utf-8") as f:
        lines = f.readlines()
    header = f"## {day}"
    try:
        start = next(i for i, l in enumerate(lines) if l.rstrip("\n") == header)
    except StopIteration:
        print(f"No entries logged for {day} yet.")
        return
    end = next((i for i in range(start + 1, len(lines)) if is_date_header(lines[i])), len(lines))
    sys.stdout.write("".join(lines[start:end]).rstrip("\n") + "\n")


def main():
    args = sys.argv[1:]
    raw = os.environ.get("WL_INPUT", "")

    if args[:1] == ["--show"]:
        show(args[1] if len(args) > 1 else TODAY)
        return
    if args[:1] == ["--manual"]:
        project = args[1] if len(args) > 1 else "General"
        text = one_line(raw, 300)
        if text:
            write_entry(project, f"- **{NOW}** 📝 {text}")
        return

    try:
        data = json.loads(raw) if raw.strip() else {}
    except ValueError:
        data = {}
    if not isinstance(data, dict):
        data = {}
    event = data.get("hook_event_name", "")
    cwd = data.get("cwd") or os.getcwd()
    project = os.path.basename(os.path.normpath(cwd)) or "General"

    if event == "SessionStart":
        branch = git(cwd, "branch", "--show-current") or "n/a"
        write_entry(project, f"- **{NOW}** 🟢 Session started (branch: `{branch}`)")
    elif event == "Stop":
        summary = stop_summary(data, cwd)
        # Only log Stop events with a meaningful summary
        if len(summary) > 5:
            write_entry(project, f"  - {NOW} ↳ {summary}")
    elif event == "SessionEnd":
        write_entry(project, session_end_entry(cwd))


try:
    main()
except Exception as exc:  # a logging hook must never break the session
    if os.environ.get("WORK_LOGGER_DEBUG"):
        raise
    print(f"work-logger: {exc}", file=sys.stderr)
PYEOF

exit 0
