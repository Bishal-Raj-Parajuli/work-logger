#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# install.sh — One-command setup for Work Logger
#
# What it does:
#   1. Copies work-logger.sh to ~/.claude/scripts/
#   2. Installs /log-entry and /daily-log as global skills
#   3. Merges hooks into ~/.claude/settings.json
#   4. Creates ~/.claude/daily-log.md if it doesn't exist
#
# Usage:
#   bash install.sh
# ─────────────────────────────────────────────────────────────

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLAUDE_DIR="$HOME/.claude"
SETTINGS_FILE="$CLAUDE_DIR/settings.json"

echo "📋 Installing Work Logger..."
echo ""

# ── 1. Install the logger script ──
echo "→ Installing work-logger.sh..."
mkdir -p "$CLAUDE_DIR/scripts"
cp "$SCRIPT_DIR/scripts/work-logger.sh" "$CLAUDE_DIR/scripts/work-logger.sh"
chmod +x "$CLAUDE_DIR/scripts/work-logger.sh"
echo "  ✓ Installed to $CLAUDE_DIR/scripts/work-logger.sh"

# ── 2. Install global skills ──
echo "→ Installing skills..."

mkdir -p "$CLAUDE_DIR/skills/log-entry"
cp "$SCRIPT_DIR/log-entry/SKILL.md" "$CLAUDE_DIR/skills/log-entry/SKILL.md"
echo "  ✓ /log-entry skill installed"

mkdir -p "$CLAUDE_DIR/skills/daily-log"
cp "$SCRIPT_DIR/daily-log/SKILL.md" "$CLAUDE_DIR/skills/daily-log/SKILL.md"
echo "  ✓ /daily-log skill installed"

# ── 3. Merge hooks into settings.json ──
echo "→ Configuring hooks..."

if [ ! -f "$SETTINGS_FILE" ]; then
    echo '{}' > "$SETTINGS_FILE"
    echo "  Created $SETTINGS_FILE"
fi

python3 << 'PYEOF'
import json, os

settings_path = os.path.expanduser("~/.claude/settings.json")

with open(settings_path, "r") as f:
    try:
        settings = json.load(f)
    except json.JSONDecodeError:
        settings = {}

work_logger_hooks = {
    "SessionStart": [
        {
            "hooks": [
                {
                    "type": "command",
                    "command": 'echo \'{"hook_event_name": "SessionStart"}\' | bash ~/.claude/scripts/work-logger.sh',
                    "timeout": 5
                }
            ]
        }
    ],
    "Stop": [
        {
            "hooks": [
                {
                    "type": "command",
                    "command": "bash ~/.claude/scripts/work-logger.sh",
                    "timeout": 5
                }
            ]
        }
    ],
    "SessionEnd": [
        {
            "hooks": [
                {
                    "type": "command",
                    "command": 'echo \'{"hook_event_name": "SessionEnd"}\' | bash ~/.claude/scripts/work-logger.sh',
                    "timeout": 5
                }
            ]
        }
    ]
}

if "hooks" not in settings:
    settings["hooks"] = {}

for event, hook_list in work_logger_hooks.items():
    if event not in settings["hooks"]:
        settings["hooks"][event] = hook_list
    else:
        existing_commands = []
        for group in settings["hooks"][event]:
            for h in group.get("hooks", []):
                existing_commands.append(h.get("command", ""))

        for group in hook_list:
            for h in group.get("hooks", []):
                if h.get("command", "") not in existing_commands:
                    settings["hooks"][event].append(group)

with open(settings_path, "w") as f:
    json.dump(settings, f, indent=2)

print("  ✓ Hooks merged into settings.json")
PYEOF

# ── 4. Create the daily log file ──
LOG_FILE="$CLAUDE_DIR/daily-log.md"
if [ ! -f "$LOG_FILE" ]; then
    cat > "$LOG_FILE" << 'EOF'
# Daily Work Log

Auto-generated by Work Logger
Entries are grouped by date → project.

EOF
    echo "  ✓ Created $LOG_FILE"
else
    echo "  ✓ $LOG_FILE already exists"
fi

echo ""
echo "───────────────────────────────────────"
echo "📋 Work Logger installed successfully!"
echo "───────────────────────────────────────"
echo ""
echo "What happens now:"
echo "  • Every Claude Code session auto-logs start/end"
echo "  • Work summaries captured after each Claude turn"
echo "  • Entries grouped by project automatically"
echo "  • All entries go to ~/.claude/daily-log.md"
echo ""
echo "Commands:"
echo "  /log-entry <text>    — Manual log entry"
echo "  /daily-log           — View today's log"
echo "  /daily-log copy      — Export for daily summary"
echo ""
echo "End-of-day:"
echo "  1. /daily-log copy           — get a clean per-project summary"
echo "  2. Paste it into your standup doc, chat thread, or AI prompt"
echo ""
