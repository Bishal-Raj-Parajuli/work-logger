#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# install.sh — One-command setup for Work Logger
#
# What it does:
#   1. Copies work-logger.sh to ~/.claude/scripts/
#   2. Installs /log-entry and /daily-log as global skills
#   3. Merges hooks into ~/.claude/settings.json
#   4. Creates ~/.claude/daily-log.md if it doesn't exist
#
# Usage:
#   bash install.sh
# ─────────────────────────────────────────────────────────────

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLAUDE_DIR="$HOME/.claude"
SETTINGS_FILE="$CLAUDE_DIR/settings.json"

echo "📋 Installing Work Logger..."
echo ""

if ! command -v python3 >/dev/null 2>&1; then
    echo "✗ python3 is required but was not found on PATH." >&2
    exit 1
fi
if ! command -v git >/dev/null 2>&1; then
    echo "  ⚠ git not found — branch and commit details will be left out of the log."
fi

# ── 1. Install the logger script ──
echo "→ Installing work-logger.sh..."
mkdir -p "$CLAUDE_DIR/scripts"
cp "$SCRIPT_DIR/scripts/work-logger.sh" "$CLAUDE_DIR/scripts/work-logger.sh"
chmod +x "$CLAUDE_DIR/scripts/work-logger.sh"
echo "  ✓ Installed to $CLAUDE_DIR/scripts/work-logger.sh"

# ── 2. Install global skills ──
echo "→ Installing skills..."

mkdir -p "$CLAUDE_DIR/skills/log-entry"
cp "$SCRIPT_DIR/log-entry/SKILL.md" "$CLAUDE_DIR/skills/log-entry/SKILL.md"
echo "  ✓ /log-entry skill installed"

mkdir -p "$CLAUDE_DIR/skills/daily-log"
cp "$SCRIPT_DIR/daily-log/SKILL.md" "$CLAUDE_DIR/skills/daily-log/SKILL.md"
echo "  ✓ /daily-log skill installed"

# ── 3. Merge hooks into settings.json ──
echo "→ Configuring hooks..."

SETTINGS_FILE="$SETTINGS_FILE" python3 << 'PYEOF'
import json, os, shutil, sys, tempfile, time

settings_path = os.environ["SETTINGS_FILE"]
COMMAND = "bash ~/.claude/scripts/work-logger.sh"

settings = {}
if os.path.exists(settings_path):
    try:
        with open(settings_path) as f:
            settings = json.load(f)
    except json.JSONDecodeError as e:
        # Never overwrite a file we can't read: that would wipe the user's config
        print(f"  ✗ {settings_path} is not valid JSON ({e}).", file=sys.stderr)
        print("    Fix it (or move it aside) and re-run install.sh. settings.json was not changed.", file=sys.stderr)
        sys.exit(1)
    if not isinstance(settings, dict):
        print(f"  ✗ {settings_path} does not contain a JSON object. It was not changed.", file=sys.stderr)
        sys.exit(1)
    backup = f"{settings_path}.bak-{time.strftime('%Y%m%d-%H%M%S')}"
    shutil.copy2(settings_path, backup)
    print(f"  ✓ Backed up existing settings to {backup}")

hooks = settings.setdefault("hooks", {})

# Drop any earlier Work Logger hooks (including older command formats)
# so re-running the installer upgrades them instead of duplicating.
for event in list(hooks):
    groups = []
    for group in hooks[event]:
        kept = [h for h in group.get("hooks", []) if "scripts/work-logger.sh" not in h.get("command", "")]
        if kept or not group.get("hooks"):
            groups.append({**group, "hooks": kept})
    hooks[event] = groups

for event in ("SessionStart", "Stop", "SessionEnd"):
    hooks.setdefault(event, []).append(
        {"hooks": [{"type": "command", "command": COMMAND, "timeout": 10}]}
    )
    if not hooks[event]:
        del hooks[event]

fd, tmp = tempfile.mkstemp(dir=os.path.dirname(settings_path), prefix=".settings.")
with os.fdopen(fd, "w") as f:
    json.dump(settings, f, indent=2)
    f.write("\n")
os.replace(tmp, settings_path)

print("  ✓ Hooks merged into settings.json")
PYEOF

# ── 4. Create the daily log file ──
LOG_FILE="${CLAUDE_DAILY_LOG:-$CLAUDE_DIR/daily-log.md}"
mkdir -p "$(dirname "$LOG_FILE")"
if [ ! -f "$LOG_FILE" ]; then
    cat > "$LOG_FILE" << 'EOF'
# Daily Work Log

Auto-generated by Work Logger
Entries are grouped by date → project.
EOF
    echo "  ✓ Created $LOG_FILE"
else
    echo "  ✓ $LOG_FILE already exists"
fi

echo ""
echo "───────────────────────────────────────"
echo "📋 Work Logger installed successfully!"
echo "───────────────────────────────────────"
echo ""
echo "What happens now:"
echo "  • Every Claude Code session auto-logs start/end"
echo "  • Work summaries captured after each Claude turn"
echo "  • Entries grouped by project automatically"
echo "  • All entries go to $LOG_FILE"
echo ""
echo "Commands:"
echo "  /log-entry <text>    — Manual log entry"
echo "  /daily-log           — View today's log"
echo "  /daily-log copy      — Export for daily summary"
echo ""
echo "End-of-day:"
echo "  1. /daily-log copy           — get a clean per-project summary"
echo "  2. Paste it into your standup doc, chat thread, or AI prompt"
echo ""
